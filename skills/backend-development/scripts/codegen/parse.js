// Bullets under "# examples" are sample VALUES (test-data defaults for
// TestDataAbility), never attributes. Only bullets outside that section
// describe the concept's structure.
function parseDefinitions(text) {
  const defs = [];
  for (const block of text.split(/^-{3,}\s*$/m)) {
    const nameLine = block.match(/^#\s*name\s+(.+)$/m);
    if (!nameLine) continue;
    const attrs = [];
    const examples = [];
    let inExamples = false;
    for (const line of block.split('\n')) {
      const heading = line.match(/^#\s*(\w+)/);
      if (heading) inExamples = heading[1].toLowerCase() === 'examples';
      const bullet = line.match(/^\*\s+(.+)$/);
      if (!bullet) continue;
      (inExamples ? examples : attrs).push(bullet[1].trim());
    }
    defs.push({ name: nameLine[1].trim(), attributes: attrs, examples });
  }
  return defs;
}

// A concept WITH listed attributes becomes a value object; without, a String.
// Both carry the definition's examples: TestDataPlugin derives test-data
// defaults from them.
function resolveTypes(defs, base) {
  const byKey = new Map();
  const valueObjects = [];
  for (const def of defs) {
    const key = naming.words(def.name).join(' ');
    if (def.attributes.length === 0) {
      byKey.set(key, { javaType: 'String', imports: [], examples: def.examples });
      continue;
    }
    const vo = naming.valueObject(base, def.name);
    const attrs = def.attributes.map((a) => ({
      name: naming.field(a),
      // a "... list" attribute is a list of names; everything else is a plain String
      javaType: /\blist$/i.test(a.trim()) ? 'List<String>' : 'String',
    }));
    // A value object with only scalar String attributes can be a JPA @Embeddable and
    // is stored as flattened columns on an owning entity; one carrying a list cannot
    // be embedded and keeps its JSON column.
    const embeds = attrs.every((a) => a.javaType === 'String');
    byKey.set(key, {
      javaType: vo.className,
      imports: [`${vo.package}.${vo.className}`],
      valueObject: vo,
      embeds,
      attrs,
      examples: def.examples,
    });
    valueObjects.push({
      kind: 'value-object',
      className: vo.className,
      package: vo.package,
      fields: attrs,
      attrs,
      embeds,
      examples: def.examples,
    });
  }
  return { byKey, valueObjects };
}

function typeOf(field, byKey) {
  if (field.convention) return CONVENTIONS[field.convention];
  const hit = byKey.get(naming.words(field.label).join(' '));
  return hit || { javaType: 'String', imports: [] };
}

// ---- top level ------------------------------------------------------------

export function parseModel({ modelDir, basePackage }) {
  const read = (f) => {
    const p = path.join(modelDir, f);
    if (!fs.existsSync(p)) throw new Error(`Missing model file: ${p}`);
    return fs.readFileSync(p, 'utf8');
  };

  const { byKey, valueObjects } = resolveTypes(
    parseDefinitions(read('business-definitions-raw.md')),
    basePackage,
  );

  const decorate = (fields) =>
    fields.map((f) => {
      const t = typeOf(f, byKey);
      return {
        ...f,
        javaType: t.javaType,
        imports: t.imports,
        conventionExpr: t.expr || null,
        ...(t.examples?.length ? { examples: t.examples } : {}),
        ...(t.valueObject ? { valueObject: t.valueObject, embeds: t.embeds, attrs: t.attrs } : {}),
      };
    });

  const events = parseSections(read('events.md')).map((s) => {
    if (!s.aggregate) throw new Error(`Event "${s.id}" has no <aggregate>:Id line`);
    if (s.headerLines.length > 1) {
      throw new Error(
        `Event "${s.id}" has more than one <aggregate>:Id line — an event always names ` +
          `exactly one aggregate; named key attributes (multiple "<path>:Key" lines) are a ` +
          `read-model-only concept.`,
      );
    }
    if (s.keyed) {
      throw new Error(
        `Event "${s.id}" uses <aggregate>:Key. ":Key" selects a persisting projection ` +
          `and is only meaningful on a read model — events always use ":Id".`,
      );
    }
    if (s.searchOnlyFields.length) {
      throw new Error(
        `Event "${s.id}" has a "??" (search-only criterion) field — search endpoints only ` +
          `exist on persisting read models, so "??" is meaningless on an event.`,
      );
    }
    return {
      id: s.id,
      name: s.props.name || s.id,
      aggregate: s.aggregate,
      fields: decorate(s.fields),
      ...naming.event(basePackage, s.id),
    };
  });
  const eventById = new Map(events.map((e) => [e.id, e]));

  const commands = parseSections(read('commands.md')).map((s) => {
    const producesId = s.props.produces;
    if (!producesId) throw new Error(`Command "${s.id}" has no "Produces:" line`);
    const produces = eventById.get(producesId);
    if (!produces) throw new Error(`Command "${s.id}" produces unknown event "${producesId}"`);
    if (s.searchOnlyFields.length) {
      throw new Error(
        `Command "${s.id}" has a "??" (search-only criterion) field — search endpoints only ` +
          `exist on persisting read models, so "??" is meaningless on a command.`,
      );
    }
    return {
      id: s.id,
      name: s.props.name || s.id,
      producesId,
      fields: decorate(s.fields),
      ...naming.command(basePackage, s.id),
    };
  });

  const readModels = parseSections(read('readmodels.md')).map((s) => {
    const subscribes = (s.props.subscribes || '').split(',').map((x) => x.trim()).filter(Boolean);
    if (subscribes.length === 0) throw new Error(`Read model "${s.id}" has no "Subscribes:" line`);
    for (const id of subscribes) {
      if (!eventById.has(id)) throw new Error(`Read model "${s.id}" subscribes unknown event "${id}"`);
    }
    if (s.headerLines.length === 0) {
      throw new Error(
        `Read model "${s.id}" has no <aggregate>:Id or <aggregate>:Key line. ` +
          `Use ":Id" for an on-demand projection (replayed per request) or ":Key" for a ` +
          `persisting one (JPA entity kept up to date on append, listable across aggregates).`,
      );
    }

    const decoratedFields = decorate(s.fields);
    const subscribedAggregates = new Set(subscribes.map((id) => eventById.get(id).aggregate));
    // Exactly one header line naming the subscribed aggregate is the classic form;
    // anything else — a second line, or a name that is not the aggregate — is a
    // named-key-attribute read model instead (see resolveKeyAttributePath above).
    const isClassic = s.headerLines.length === 1 && subscribedAggregates.has(s.headerLines[0].name);

    let aggregate, keyed, fields, headerKeyFields;
    if (isClassic) {
      aggregate = s.headerLines[0].name;
      keyed = s.headerLines[0].mode === 'Key';
      fields = injectIdentity(s, decoratedFields);
      headerKeyFields = [];
    } else {
      aggregate = null;
      keyed = true; // a composite natural key always needs a table to be looked up by
      fields = decoratedFields; // no implicit identity component in this mode
      headerKeyFields = s.headerLines.map(({ name, mode }) => {
        if (mode !== 'Key') {
          throw new Error(
            `Read model "${s.id}" names key attribute "${name}:${mode}" — a named key ` +
              `attribute (anything other than the single "<aggregate>:Id|Key" line naming ` +
              `the subscribed aggregate "${[...subscribedAggregates].join('/')}") must use ` +
              `":Key". ":Id" only selects the classic single-aggregate on-demand form.`,
          );
        }
        const resolved = resolveKeyAttributePath(name, decoratedFields);
        if (!resolved) {
          throw new Error(
            `Read model "${s.id}" names key attribute "${name}:Key" but no declared field's ` +
              `value-object attribute matches that path. It must decompose into an already-` +
              `declared field ("* <value-object field>") followed by exactly one of that ` +
              `value object's own attributes — e.g. "policyHolderName" needs a field ` +
              `"* policy holder" whose value object has an attribute "name". Add the missing ` +
              `field or fix the name; the generator does not guess.`,
          );
        }
        return {
          // The header line's name IS the camelCase field name already (unlike a
          // "* label" field, whose label still needs naming.field()'s space/hyphen
          // splitting) — running it through naming.field() here would flatten the
          // camelCase boundaries it already has (naming.field only splits on
          // whitespace/hyphen/underscore) into a single lowercased word.
          name: name[0].toLowerCase() + name.slice(1),
          label: name,
          key: true,
          javaType: resolved.attr.javaType,
          imports: [],
          derivedFrom: { field: resolved.field.name, attr: resolved.attr.name },
        };
      });
    }

    const keyFields = [...headerKeyFields, ...fields.filter((f) => f.key)];
    if (keyFields.length && !keyed) {
      throw new Error(
        `Read model "${s.id}" marks field(s) with ":Key" but is not a persisting ` +
          `("<aggregate>:Key") projection. ":Key" fields are only meaningful on a ` +
          `persisting read model, where they compose its composite id.`,
      );
    }
    if (s.searchOnlyFields.length && !keyed) {
      throw new Error(
        `Read model "${s.id}" has a "??" (search-only criterion) field but is an on-demand ` +
          `("<aggregate>:Id") projection — the search endpoint (and its Map<String,String> ` +
          `search param) only exists on a persisting ("<aggregate>:Key") read model.`,
      );
    }
    // Decorated the same way as regular fields (so a search-only criterion named
    // after a business concept gets the right javaType), but never merged into
    // `fields` — see parseSearchOnlyField.
    const searchOnlyFields = decorate(s.searchOnlyFields);

    // A "??" criterion has no stored value, so its decider (`matches<Field>`) can
    // only compute a match from data the read model's OWN fields actually carry —
    // there is no collaborator wiring, no hidden state, nothing else it can reach
    // for (the decider keeps a no-arg constructor forever). If not one field label
    // or value-object attribute even shares a word with the criterion, implementing
    // it silently would mean inventing data out of nothing — a decision for the
    // architect (add the underlying field, or confirm the criterion belongs
    // elsewhere), not something to guess your way through in a decider body. Fail
    // the model here, loudly, instead of letting an agent discover the gap only
    // after already writing a stub decider full of private state.
    requireSearchOnlyFieldsHaveData(s.id, fields, s.searchOnlyFields);

    return {
      id: s.id,
      name: s.props.name || s.id,
      aggregate,
      onDemand: !keyed,
      keyed,
      subscribes,
      fields,
      keyFields,
      searchOnlyFields,
      ...naming.readModel(basePackage, s.id, { keyed }),
    };
  });

  return { meta: { basePackage }, valueObjects, events, commands, readModels };
}

export { parseSections, parseField, parseSearchOnlyField, parseDefinitions, CONVENTIONS };
