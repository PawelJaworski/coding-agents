// A smoke test that the generated wiring really reaches the backend contract.
// It is yours: frontend-implement adds the GWT scenarios alongside it.
function spec(page) {
  const wired = page.views.length > 0 || page.commands.length > 0;
  const endpointImports = page.views.map((v) =>
    v.collection ? `${constName(v.id)}_ENDPOINT` : `${naming.camel(v.id)}Endpoint`,
  );

  const lines = [
    ONCE.trimEnd(),
    `import { TestBed } from '@angular/core/testing';`,
    `import { provideRouter } from '@angular/router';`,
  ];
  if (wired) {
    lines.push(`import { provideHttpClient } from '@angular/common/http';`);
    lines.push(
      `import {\n  HttpTestingController,\n  provideHttpClientTesting,\n} from '@angular/common/http/testing';`,
    );
  }
  lines.push(`import { ${page.className} } from './${page.componentFile.replace(/\.ts$/, '')}';`);
  if (endpointImports.length) {
    lines.push(
      `import {\n${endpointImports.map((e) => `  ${e},`).join('\n')}\n} from './${page.contractsFile.replace(/\.ts$/, '')}';`,
    );
  }
  lines.push('');
  lines.push(`describe('${page.className}', () => {`);
  if (wired) lines.push('  let http: HttpTestingController;');
  lines.push('');
  lines.push('  beforeEach(async () => {');
  lines.push('    await TestBed.configureTestingModule({');
  lines.push(`      imports: [${page.className}],`);
  lines.push('      providers: [');
  lines.push('        provideRouter([]),');
  if (wired) lines.push('        provideHttpClient(),\n        provideHttpClientTesting(),');
  lines.push('      ],');
  lines.push('    }).compileComponents();');
  if (wired) lines.push('    http = TestBed.inject(HttpTestingController);');
  lines.push('  });');
  if (wired) {
    lines.push('');
    lines.push('  afterEach(() => http.verify());');
  }
  lines.push('');
  lines.push(`  it('renders and requests exactly what the event model wires it to', async () => {`);
  lines.push(`    const fixture = TestBed.createComponent(${page.className});`);
  lines.push('    await fixture.whenStable();');
  for (const v of page.views) {
    const url = v.collection
      ? `${constName(v.id)}_ENDPOINT`
      : `${naming.camel(v.id)}Endpoint('')`;
    lines.push('');
    lines.push(`    // GET ${v.id} fires on init because uis.md wires this page to it`);
    lines.push(`    http.expectOne(${url}).flush(${v.collection ? '[]' : 'null'});`);
    lines.push('    await fixture.whenStable();');
  }
  lines.push('');
  lines.push(`    expect(fixture.nativeElement.querySelector('h1')?.textContent)`);
  lines.push(`      .toContain('${page.name}');`);
  lines.push('  });');
  lines.push('});');
  return lines.join('\n') + '\n';
}

function routes(pages) {
  if (!pages.length) return GEN + `import { Routes } from '@angular/router';\n\nexport const pageRoutes: Routes = [];\n`;
  const imports = pages
    .map((p) => `import { ${p.className} } from './${p.dir}/${p.componentFile.replace(/\.ts$/, '')}';`)
    .join('\n');
  const entries = pages
    .map((p) => `  { path: '${p.routePath}', component: ${p.className}, title: '${p.name}' },`)
    .join('\n');
  return (
    GEN +
    `import { Routes } from '@angular/router';\n${imports}\n\n` +
    `/** One route per \`Type: html\` entry in uis.md. Spread this into app.routes.ts. */\n` +
    `export const pageRoutes: Routes = [\n${entries}\n];\n`
  );
}

export function emit(model, { pagesRoot, apiBase }) {
  const files = [];
  const at = (page, file) => `${pagesRoot}/${page.dir}/${file}`;

  for (const page of model.pages) {
    files.push({ path: at(page, page.contractsFile), content: contracts(page, apiBase) });
    files.push({ path: at(page, page.apiFile), content: api(page) });
    files.push({ path: at(page, page.componentFile), content: component(page) });
    files.push({ path: at(page, page.importsFile), content: pageImports(page), once: true });
    files.push({ path: at(page, page.storeFile), content: store(page), once: true });
    files.push({ path: at(page, page.templateFile), content: template(page), once: true });
    files.push({ path: at(page, page.styleFile), content: style(page), once: true });
    files.push({ path: at(page, page.specFile), content: spec(page), once: true });
  }
  files.push({ path: `${pagesRoot}/pages.routes.ts`, content: routes(model.pages) });
  return files;
}

export { contracts, api, component, pageImports, store, template, spec, routes };
